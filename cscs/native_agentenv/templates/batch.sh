#!/usr/bin/env bash
set -euo pipefail
set +x
# Slurm spools this file; SLURM_SUBMIT_DIR points at the frozen run directory.
set -a
source "${SLURM_SUBMIT_DIR}/launch.env"
source "${AGENTENV_CREDENTIALS}"
set +a
: "${AGENTENV_API_KEY:?Missing AGENTENV_API_KEY in credential file}"
export SLURM_EXPORT_ENV=ALL
export EDF_PATH="${RUN_DIR}:${EDF_PATH:-}"
export TMPDIR=/tmp
export PIP_CACHE_DIR="${WORK_ROOT}/pip-cache"
export PYTHONPATH="${REPO_DIR}:${REPO_DIR}/verl:${NATIVE_SHELL_ROOT}"
mkdir -p "${WORK_ROOT}/home" "${WORK_ROOT}/hf" "${PIP_CACHE_DIR}" "${AGENTENV_TRACE_DIR}"
CLUSTER_NNODES=${SLURM_NNODES}
NNODES_T=${CLUSTER_NNODES}
NNODES=$((CLUSTER_NNODES - NNODES_ROLLOUT))
[[ ${NNODES} -gt 0 ]] || { echo 'Allocation must exceed rollout node count.' >&2; exit 1; }
mapfile -t ALLOCATED_NODES < <(scontrol show hostnames "${SLURM_JOB_NODELIST}")
HEAD_NODE=${ALLOCATED_NODES[0]}
# Bind Ray to a job-specific port to avoid colliding with another allocation.
RAY_PORT=$((10000 + SLURM_JOB_ID % 40000))
RAY_TMPDIR="/tmp/ray-${SLURM_JOB_ID}"
if [[ -n ${WANDB_API_KEY:-} ]]; then
    LOGGER="['console','wandb']"
else
    LOGGER="['console']"
fi
RUN_ENV=(
    "REPO_DIR=${REPO_DIR}" "WORK_ROOT=${WORK_ROOT}" "RUN_DIR=${RUN_DIR}"
    "TRAIN_SCRIPT=${TRAIN_SCRIPT}" "RUNTIME_DIR=${RUNTIME_DIR}" "DATA_DIR=${DATA_DIR}"
    "RUNTIME_ENV=${RUNTIME_ENV}" "TASK_CONFIG=${TASK_CONFIG}"
    "MODEL_PATH=${MODEL_PATH}" "TRAIN_FILE=${TRAIN_FILE}" "TEST_FILE=${TEST_FILE}"
    "CKPTS_DIR=${CKPTS_DIR}" "AGENT_LOG_DIR=${AGENT_LOG_DIR}"
    "AGENTENV_ENDPOINT=${AGENTENV_ENDPOINT}" "AGENTENV_API_KEY=${AGENTENV_API_KEY}"
    "AGENTENV_TRACE_DIR=${AGENTENV_TRACE_DIR}" "NATIVE_SHELL_ROOT=${NATIVE_SHELL_ROOT}"
    "HARBOR_VENV=${HARBOR_VENV}" "PYTHONPATH=${PYTHONPATH}"
    "TRAINING_STEPS=${TRAINING_STEPS}" "SAVE_FREQ=${SAVE_FREQ}"
    "PROJECT_NAME=${PROJECT_NAME}" "EXP_NAME=${EXP_NAME}"
    "NNODES=${NNODES}" "NNODES_T=${NNODES_T}" "NNODES_ROLLOUT=${NNODES_ROLLOUT}"
    "TRAINER_MODE=${TRAINER_MODE}" "PARAMETER_SYNC_STEP=${PARAMETER_SYNC_STEP}"
    "HEAD_NODE=${HEAD_NODE}" "RAY_PORT=${RAY_PORT}" "RAY_TMPDIR=${RAY_TMPDIR}"
    "GPUS_PER_NODE=${GPUS_PER_NODE}" "NGPUS_PER_NODE=${NGPUS_PER_NODE}" "CPUS_PER_NODE=${CPUS_PER_NODE}"
    "GEN_TP=${GEN_TP}" "TP=${TP}" "PP=${PP}" "CP=${CP}"
    "CONCURRENCY=${CONCURRENCY}" "TRAIN_PROMPT_BSZ=${TRAIN_PROMPT_BSZ}"
    "N_RESP_PER_PROMPT=${N_RESP_PER_PROMPT}" "PPO_MINI_BATCH_SIZE=${PPO_MINI_BATCH_SIZE}"
    "VLLM_GPU_MEM_UTIL=${VLLM_GPU_MEM_UTIL}" "MAX_PROMPT_LENGTH=${MAX_PROMPT_LENGTH}"
    "MAX_RESPONSE_LENGTH=${MAX_RESPONSE_LENGTH}" "SANDBOX_START_RETRIES=${SANDBOX_START_RETRIES}"
    "SANDBOX_START_ATTEMPT_TIMEOUT=${SANDBOX_START_ATTEMPT_TIMEOUT}"
    "SANDBOX_START_RETRY_BACKOFF=${SANDBOX_START_RETRY_BACKOFF}"
    "TMPDIR=/tmp" "PIP_CACHE_DIR=${PIP_CACHE_DIR}" "LOGGER=${LOGGER}"
)
if [[ -n ${WANDB_API_KEY:-} ]]; then
    RUN_ENV+=("WANDB_API_KEY=${WANDB_API_KEY}" "WANDB_ENTITY=${WANDB_ENTITY:-}")
fi
echo "[launch] Native AgentENV; ${NNODES} trainer + ${NNODES_ROLLOUT} rollout nodes; concurrency ${CONCURRENCY}"
cd "${REPO_DIR}"
srun --export=ALL,TMPDIR=/tmp --nodes="${CLUSTER_NNODES}" --ntasks="${CLUSTER_NNODES}" \
    --ntasks-per-node=1 --cpus-per-task="${CPUS_PER_NODE}" --gpus-per-task="${GPUS_PER_NODE}" \
    --environment="${ENV_NAME}" env "${RUN_ENV[@]}" bash "${RUN_DIR}/run_ray_node.sh"
